x = float(input("Введите координату x: "))
y = float(input("Введите координату y: "))
axis = (0 <= x <= 5) and (0 <= y <= 3)
if not axis:
    print("Координаты снаружи прямоугольника")
elif x == 0 or x == 5 or y == 0 or y == 3:
    print("Координаьы на границе прямоугольника")
else:
    print("Координаты внутри прямоугольника")